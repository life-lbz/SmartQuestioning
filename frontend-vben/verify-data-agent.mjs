import { chromium } from 'playwright';
import { writeFile } from 'node:fs/promises';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: {width: 1440, height: 1000} });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
await page.goto('http://127.0.0.1:5180', {waitUntil:'networkidle', timeout:120000});
await page.getByText('数据库已连接', {exact:true}).waitFor();
await page.locator('canvas').waitFor();
await page.screenshot({path:'../.runtime/vben-migration/workbench.png',fullPage:true});
console.log((await page.locator('body').innerText()).slice(0,5000));
await page.getByLabel('结果视图').click();
await page.getByText('数据表格', {exact:true}).last().click();
await page.getByRole('columnheader', {name:'month',exact:true}).waitFor();
await page.getByLabel('业务问题', {exact:true}).fill('销售额最高的前 10 个商品');
await page.getByRole('button',{name:'执行查询',exact:true}).click();
await page.getByRole('button',{name:'确认执行',exact:true}).waitFor();
await page.getByRole('button',{name:'确认执行',exact:true}).click();
await page.getByRole('columnheader', {name:'product',exact:true}).waitFor();
await page.getByText('SQL 与查询口径', {exact:true}).click();
await page.getByRole('code').count();
await page.getByRole('menuitem').filter({hasText:'数据目录'}).click();
await page.getByRole('columnheader', {name:'字段名',exact:true}).first().waitFor();
await page.screenshot({path:'../.runtime/vben-migration/catalog.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.goto('http://127.0.0.1:5180/workbench', {waitUntil:'networkidle'});
await page.getByText('数据库已连接', {exact:true}).waitFor();
await page.screenshot({path:'../.runtime/vben-migration/mobile.png',fullPage:true});
const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
console.log('MOBILE_OVERFLOW',overflow);
if (overflow) errors.push('Mobile viewport has horizontal overflow');
await writeFile('../.runtime/vben-migration/browser-errors.json',JSON.stringify(errors,null,2));
await browser.close();
if (errors.length) throw new Error(errors.join('\n'));
