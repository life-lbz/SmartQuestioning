import { chromium } from 'playwright';
import { readFile,writeFile } from 'node:fs/promises';
const secret=await readFile('../.runtime/platform/initial-admin.txt','utf8');
const password=secret.split(/\r?\n/).find(x=>x.startsWith('password=')).slice(9);
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8013/login',{waitUntil:'networkidle'});
await page.getByLabel('账号',{exact:true}).fill('admin');
await page.getByLabel('密码',{exact:true}).fill(password);
await page.locator('button[type="submit"]').click();
await page.waitForURL('**/overview');
await page.locator('.metric-caption, .kpi-label').filter({hasText:'订单总量'}).waitFor();
await page.locator('canvas').waitFor();
await page.waitForTimeout(1600);
await page.screenshot({path:'../.runtime/commercial-v1/overview.png',fullPage:true});
await page.getByText('近6月',{exact:true}).click();
await page.getByText('柱状',{exact:true}).click();
await page.waitForTimeout(1600);
await page.screenshot({path:'../.runtime/chart-upgrade/bar.png',fullPage:true});
console.log((await page.locator('body').innerText()).slice(0,2000));
await page.getByRole('menuitem').filter({hasText:'用户管理'}).click();
await page.getByRole('button',{name:'新增用户',exact:true}).waitFor();
await page.screenshot({path:'../.runtime/commercial-v1/users.png',fullPage:true});
await page.getByRole('menuitem').filter({hasText:'查询工作台'}).click();
await page.getByRole('button',{name:'执行查询',exact:true}).click();
await page.getByText('导出 CSV',{exact:true}).waitFor();
await page.getByRole('button',{name:'收藏当前查询',exact:true}).click();
await page.getByText('已保存到收藏查询',{exact:true}).waitFor();
await page.getByRole('menuitem').filter({hasText:'查询历史'}).click();
await page.getByRole('button',{name:/查\s*看/}).first().waitFor();
await page.screenshot({path:'../.runtime/commercial-v1/history.png',fullPage:true});
await writeFile('../.runtime/commercial-v1/preview.json',JSON.stringify({errors,login:true,overview:true,users:true,query:true,favorite:true,history:true},null,2));
await browser.close();
if(errors.length)throw new Error(errors.join('\n'));
